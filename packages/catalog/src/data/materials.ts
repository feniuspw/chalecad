type Cat = Material['category'];
type Unit = Material['baseUnit'];

interface Opts {
  sheet?: { width: number; height: number };
  integer?: boolean;
}

function m(
  id: string,
  name: string,
  category: Cat,
  baseUnit: Unit,
  label: string,
  size: number,
  massPerUnit: number,
  wastePct: number,
  opts: Opts = {},
): Material {
  const purchase: Material['purchase'] = { label, size, integer: opts.integer ?? true };
  if (opts.sheet) purchase.sheet = opts.sheet;
  return { id, name, category, baseUnit, purchase, wastePct, massPerUnit, priceItemId: `mat-${id}`, laborIncluded: false };
}

